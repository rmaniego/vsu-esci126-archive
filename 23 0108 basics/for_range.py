# range function - start, stop, and step

print("\nExample #1:")
for number in range(4):
    print(number)

print("\nExample #2:")
for number in range(1, 4):
    print(number)

print("\nExample #3:")
for number in range(1, 10, 3):
    print(number)

print("\nExample #4:")
for number in range(99, 95, -1):
    print(number)